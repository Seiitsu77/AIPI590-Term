"""Render FEASIBILITY.md from the machine-readable results.

Every number in the report is read from results/feasibility_report.json or from the
download manifests. None is typed by hand, so the prose cannot drift from the output.

Usage:
    python src/report.py
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
RESULTS = ROOT / "results"

PRIMARY = "spearman_within_season"
METRIC_LABELS = {
    "spearman_within_season": "Within-season Spearman",
    "r2_within_season": "Within-season R²",
    "top_quintile_hit_rate": "Top-quintile hit rate",
    "ndcg_at_10": "NDCG@10",
}
ARM_LABELS = {
    "meta": "Metadata only (baseline)",
    "meta+alt": "Metadata + pre-air pageviews",
    "alt_only": "Pre-air pageviews only",
    "meta+en": "Metadata + English pageviews",
    "meta+ja": "Metadata + Japanese pageviews",
    "meta+zh": "Metadata + Chinese pageviews",
    "meta+postair_LOOKAHEAD": "Metadata + post-air pageviews (look-ahead)",
}
SAMPLE_LABELS = {
    "tv_mapped": "TV, mapped to an article (primary)",
    "tv_all": "TV, all titles (unmapped get zero views)",
    "all_types_mapped": "All formats, mapped to an article",
}


def pct(value: float) -> str:
    return f"{100 * value:.1f}%"


def interval(triple: list[float]) -> str:
    delta, low, high = triple
    return f"{delta:+.3f} [{low:+.3f}, {high:+.3f}]"


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(header))) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def coverage_table(block: dict, first_column: str) -> str:
    header = [first_column, "n", "In Wikidata", "English", "Japanese", "Chinese", "Any article", "Pre-air views > 0"]
    rows = []
    for key, row in block.items():
        rows.append(
            [str(key), str(int(row["n"])), pct(row["in_wikidata"]), pct(row["mapped_en"]), pct(row["mapped_ja"]),
             pct(row["mapped_zh"]), pct(row["mapped_any"]), pct(row["preair_views_any"])]
        )  # fmt: skip
    return table(header, rows)


def main() -> None:
    report = json.loads((RESULTS / "feasibility_report.json").read_text(encoding="utf-8"))
    wikidata = json.loads((RAW / "wikidata_manifest.json").read_text(encoding="utf-8"))
    pageviews = json.loads((RAW / "pageviews_manifest.json").read_text(encoding="utf-8"))
    catalog_sha = hashlib.sha256((RAW / "anime.csv").read_bytes()).hexdigest()

    decision = report["decision"]
    primary = report["results"]["tv_mapped"]["ridge"]
    out: list[str] = []
    add = out.append

    add("# Feasibility check: do pre-air Wikipedia pageviews predict an anime's audience beyond metadata?")
    add("")
    add(f"**Verdict against the rule fixed in advance: {decision['verdict']}.** Adding pre-air pageviews to the metadata baseline "
        f"changes the within-season rank correlation by **{interval([decision['delta'], *decision['ci95']])}** "
        f"(point estimate and 95% paired bootstrap interval, {primary['n_test']} test titles).")  # fmt: skip
    add("")
    add("This file is generated by `src/report.py` from `results/feasibility_report.json`. No number in it is typed by hand.")
    add("")

    add("## 1. Question and decision rule")
    add("")
    add("A new anime has no ratings on the day it premieres, so a collaborative-filtering recommender cannot score it. "
        "Metadata (studio, source material, franchise) is known in advance. So is the attention the show's Wikipedia "
        "article received in the weeks before the premiere. The question is whether that attention predicts how many "
        "people end up liking the show **over and above** what metadata already predicts.")  # fmt: skip
    add("")
    add("All definitions were fixed in `src/analyze.py` before any feature was compared against the outcome:")
    add("")
    d = report["definitions"]
    add(f"- **Outcome:** {d['outcome']}.")
    add(f"- **Alt-data features:** per language (en, ja, zh), log pageviews on days {d['pre_air_window_days'][0]} to "
        f"{d['pre_air_window_days'][1]} and on days {d['baseline_window_days'][0]} to {d['baseline_window_days'][1]} "
        "relative to the premiere, summed over the title's own article and its parent (series or source-work) article.")  # fmt: skip
    add("- **Baseline:** type, source, age rating, genres, episode count, premiere quarter, studio prior, franchise prior.")
    add(f"- **Split:** train on {d['train']}; test on {d['test']}. Temporal, never random.")
    add("- **Model:** ridge regression; scaling and penalty chosen on the training set only.")
    add("- **Primary metric:** Spearman rank correlation computed inside each premiere season, then averaged.")
    add(f"- **Decision rule:** {decision['rule']}; otherwise FAIL. {d['bootstrap_draws']} paired bootstrap draws, seed {d['seed']}.")
    add("")

    add("## 2. Data")
    add("")
    add(table(
        ["Source", "What", "Retrieved", "Identity"],
        [
            ["Anime Recommendation Database 2020 (Kaggle, CC0)", "`anime.csv`, MAL catalog snapshot of early 2021", "copied from the Anime Compass archive", f"SHA-256 `{catalog_sha[:16]}…`"],
            ["Wikidata SPARQL", f"{wikidata['wikidata_rows_with_mal_id']:,} items carrying {wikidata['property']} ({wikidata['property_label_verified']})", wikidata["retrieved_utc"], f"SHA-256 `{wikidata['sha256'][:16]}…`"],
            ["Wikimedia pageviews API", f"daily views, {pageviews['articles']:,} articles, {pageviews['first_day']} to {pageviews['last_day']}, agent = user", pageviews["last_run_finished_utc"], "status " + ", ".join(f"{k}: {v:,}" for k, v in pageviews["status"].items())],
        ],
    ))  # fmt: skip
    add("")

    add("## 3. Coverage: where the holes are")
    add("")
    add("Share of cohort titles at each mapping stage. \"Pre-air views > 0\" is the only column that is point-in-time; "
        "the others describe today's Wikidata and Wikipedia.")  # fmt: skip
    add("")
    add("**By format**")
    add("")
    add(coverage_table(report["coverage"]["by_type"], "Format"))
    add("")
    add("**TV titles by eventual popularity** (fifths of the outcome)")
    add("")
    add(coverage_table(report["coverage"]["tv_by_popularity"], "Popularity fifth"))
    add("")
    add("**TV titles, new versus sequel**")
    add("")
    add(coverage_table(report["coverage"]["tv_by_sequel"], "Kind"))
    add("")
    add("![Coverage by popularity](figures/fig1_coverage_by_popularity.png)")
    add("")

    add("## 4. Primary result")
    add("")
    add(f"TV titles with a mapped article. Train {primary['n_train']}, test {primary['n_test']}.")
    add("")
    arms = ("meta", "meta+alt", "alt_only")
    add(table(
        ["Information set", *[METRIC_LABELS[m] for m in METRIC_LABELS]],
        [[ARM_LABELS[arm], *[f"{primary['arms'][arm][m]:.3f}" for m in METRIC_LABELS]] for arm in arms],
    ))  # fmt: skip
    add("")
    add("Change from adding pre-air pageviews to metadata, with 95% paired bootstrap intervals:")
    add("")
    add(table(
        ["Metric", "Metadata + pageviews minus metadata"],
        [[METRIC_LABELS[m] + (" (primary)" if m == PRIMARY else ""), interval(primary["delta_vs_meta"]["meta+alt"][m])] for m in METRIC_LABELS],
    ))  # fmt: skip
    add("")
    add("![Increment over metadata](figures/fig3_increment_over_metadata.png)")
    add("")
    add("![Ranking by information set](figures/fig4_ranking_by_information_set.png)")
    add("")

    add("## 5. Secondary analyses (not part of the decision)")
    add("")
    add("**New titles versus sequels** (primary sample, ridge)")
    add("")
    add(table(
        ["Subgroup", "n test", "Metadata", "Metadata + pageviews", "Change [95% CI]"],
        [[label, str(primary["subgroups"][key]["n_test"]),
          f"{primary['subgroups'][key]['arms']['meta'][PRIMARY]:.3f}",
          f"{primary['subgroups'][key]['arms']['meta+alt'][PRIMARY]:.3f}",
          interval(primary["subgroups"][key]["delta_vs_meta"]["meta+alt"][PRIMARY])]
         for key, label in (("new_ip", "New titles"), ("sequel", "Sequels"))],
    ))  # fmt: skip
    add("")
    add("**One test year at a time** (train on all earlier premieres)")
    add("")
    add(table(
        ["Test year", "n train", "n test", "Metadata", "Metadata + pageviews", "Change [95% CI]"],
        [[year, str(b["n_train"]), str(b["n_test"]), f"{b['meta']:.3f}", f"{b['meta+alt']:.3f}", interval(b["delta"])]
         for year, b in report["by_test_year"].items()],
    ))  # fmt: skip
    add("")
    add("**Other samples and a non-linear model**")
    add("")
    rows = []
    for sample, label in SAMPLE_LABELS.items():
        block = report["results"].get(sample, {})
        if "skipped" in block:
            rows.append([label, "—", "—", "—", "—", f"skipped: {block['skipped']}"])
            continue
        for model in ("ridge", "boosted"):
            b = block[model]
            rows.append([label, model, str(b["n_test"]), f"{b['arms']['meta'][PRIMARY]:.3f}", f"{b['arms']['meta+alt'][PRIMARY]:.3f}",
                         interval(b["delta_vs_meta"]["meta+alt"][PRIMARY])])  # fmt: skip
    add(table(["Sample", "Model", "n test", "Metadata", "Metadata + pageviews", "Change [95% CI]"], rows))
    add("")
    add("**Which language carries the signal** (primary sample, ridge; each row adds one language's two features to metadata)")
    add("")
    add(table(
        ["Added to metadata", "Within-season Spearman", "Change [95% CI]"],
        [[ARM_LABELS[arm], f"{primary['arms'][arm][PRIMARY]:.3f}", interval(primary["delta_vs_meta"][arm][PRIMARY])]
         for arm in ("meta+en", "meta+ja", "meta+zh", "meta+alt")],
    ))  # fmt: skip
    add("")
    add("**Single-feature rank correlation with the outcome** (primary sample, not within season)")
    add("")
    uni = report["univariate_spearman_with_outcome"]
    add(table(["Feature", "Train 2016-2018", "Test 2019-2020"], [[f"`{k}`", f"{uni['train'][k]:.3f}", f"{uni['test'][k]:.3f}"] for k in uni["train"]]))
    add("")
    add("![Pre-air views versus audience](figures/fig2_preair_views_vs_audience.png)")
    add("")
    add("![Attention around the premiere](figures/fig5_attention_around_premiere.png)")
    add("")

    add("## 6. Look-ahead demonstration")
    add("")
    post = primary["arms"]["meta+postair_LOOKAHEAD"][PRIMARY]
    add(f"Replacing the pre-air window with pageviews from the first 28 days **after** the premiere gives a within-season "
        f"Spearman of {post:.3f}, against {primary['arms']['meta+alt'][PRIMARY]:.3f} for the pre-air window. That arm is "
        "not a result. It uses information a cold-start system would not have, and it is shown only to size how much an "
        "accidental window error would flatter the model.")  # fmt: skip
    add("")

    diag = report["diagnostics"]
    add("## 7. A measurement defect found after the test")
    add("")
    add(f"Of the {diag['tv_top_fifth_mapped']} mapped TV titles in the most popular fifth, "
        f"**{diag['tv_top_fifth_mapped_but_zero_preair_views']} show no pre-air pageviews in any language**. "
        "The largest are: " + "; ".join(diag["largest_silent_titles"]) + ".")  # fmt: skip
    add("")
    add("These are not shows nobody looked up. The pre-specified mapping took a title's own article plus its *nearest* "
        "parent, which for these titles resolved to \"… season 1\" and \"… (TV series)\" pages. Both were split out of "
        "the main article years after the premiere, so they had no views beforehand. The attention was on the main "
        "article, which Wikidata models as the source manga, one step further up the chain. The test as specified "
        "therefore could not see the signal for exactly the titles where it should be strongest, which biases it "
        "toward finding nothing.")  # fmt: skip
    add("")
    add("![Pre-air views versus audience, pre-specified mapping](figures/fig2_preair_views_vs_audience.png)")
    add("")

    exploratory_path = RESULTS / "exploratory_feasibility_report.json"
    if exploratory_path.exists():
        explo = json.loads(exploratory_path.read_text(encoding="utf-8"))
        e_primary = explo["results"]["tv_mapped"]["ridge"]
        add("## 8. Exploratory (post hoc): corrected article mapping")
        add("")
        add("**This section was produced after the result in section 4 had been read. It cannot change that verdict.** "
            "The mapping is extended on principle, not by trying alternatives against the outcome: a title's attention "
            "is summed over its own article, its series article and the article of the work it is based on "
            "(`src/map_wikipedia_exploratory.py`). The rows, split, features, model and metric are unchanged.")  # fmt: skip
        add("")

        def cell(block: dict, model: str, arm: str) -> str:
            return f"{block['results']['tv_mapped'][model]['arms'][arm][PRIMARY]:.3f}"

        def change(block: dict, model: str, sample: str = "tv_mapped") -> str:
            return interval(block["results"][sample][model]["delta_vs_meta"]["meta+alt"][PRIMARY])

        rows = [
            ["Top-fifth mapped titles with zero pre-air views", str(diag["tv_top_fifth_mapped_but_zero_preair_views"]), str(explo["diagnostics"]["tv_top_fifth_mapped_but_zero_preair_views"])],
            ["Pageviews only, within-season Spearman (ridge)", cell(report, "ridge", "alt_only"), cell(explo, "ridge", "alt_only")],
            ["Metadata only (ridge)", cell(report, "ridge", "meta"), cell(explo, "ridge", "meta")],
            ["Metadata + pageviews (ridge)", cell(report, "ridge", "meta+alt"), cell(explo, "ridge", "meta+alt")],
            ["**Change from adding pageviews, ridge (the pre-specified comparison)**", change(report, "ridge"), change(explo, "ridge")],
            ["Change from adding pageviews, boosted trees", change(report, "boosted"), change(explo, "boosted")],
            ["Change, new titles only (ridge)", interval(primary["subgroups"]["new_ip"]["delta_vs_meta"]["meta+alt"][PRIMARY]), interval(e_primary["subgroups"]["new_ip"]["delta_vs_meta"]["meta+alt"][PRIMARY])],
            ["Change, all TV titles incl. unmapped (ridge)", change(report, "ridge", "tv_all"), change(explo, "ridge", "tv_all")],
            ["Change in NDCG@10, boosted trees", interval(report["results"]["tv_mapped"]["boosted"]["delta_vs_meta"]["meta+alt"]["ndcg_at_10"]), interval(explo["results"]["tv_mapped"]["boosted"]["delta_vs_meta"]["meta+alt"]["ndcg_at_10"])],
            ["Look-ahead arm: change from post-air pageviews, boosted trees", interval(report["results"]["tv_mapped"]["boosted"]["delta_vs_meta"]["meta+postair_LOOKAHEAD"][PRIMARY]), interval(explo["results"]["tv_mapped"]["boosted"]["delta_vs_meta"]["meta+postair_LOOKAHEAD"][PRIMARY])],
        ]  # fmt: skip
        for lang, label in (("en", "English"), ("ja", "Japanese"), ("zh", "Chinese")):
            key = f"pv_pre30_{lang}"
            rows.append([f"{label} pre-air views, rank correlation with outcome (test)", f"{report['univariate_spearman_with_outcome']['test'][key]:.3f}", f"{explo['univariate_spearman_with_outcome']['test'][key]:.3f}"])  # fmt: skip
        add(table(["TV titles with a mapped article", "Pre-specified mapping", "Exploratory mapping"], rows))
        add("")
        e_delta = e_primary["delta_vs_meta"]["meta+alt"][PRIMARY]
        add(f"Under the corrected mapping the pre-specified comparison gives {interval(e_delta)}, which "
            f"{'would meet' if e_delta[0] > 0 and e_delta[1] > 0 else 'still does not meet'} the decision rule. "
            "One test year at a time:")  # fmt: skip
        add("")
        add(table(
            ["Test year", "n test", "Metadata", "Metadata + pageviews", "Change [95% CI]"],
            [[year, str(b["n_test"]), f"{b['meta']:.3f}", f"{b['meta+alt']:.3f}", interval(b["delta"])] for year, b in explo["by_test_year"].items()],
        ))  # fmt: skip
        add("")
        add("![Exploratory: pre-air views versus audience](figures/exploratory_fig2_preair_views_vs_audience.png)")
        add("")
        add("![Exploratory: increment over metadata](figures/exploratory_fig3_increment_over_metadata.png)")
        add("")
        add("![Exploratory: ranking by information set](figures/exploratory_fig4_ranking_by_information_set.png)")
        add("")
        add("![Exploratory: attention around the premiere](figures/exploratory_fig5_attention_around_premiere.png)")
        add("")

    after_path = RESULTS / "exploratory_after_premiere_report.json"
    if after_path.exists():
        after = json.loads(after_path.read_text(encoding="utf-8"))
        horizons = after["definitions"]["horizons_days_after_premiere"]
        headline = f"meta+pre+first{after['definitions']['headline_horizon']}"
        add("## 9. Exploratory (post hoc): the first days after the premiere")
        add("")
        add("**Also produced after the results above had been read.** The look-ahead arm showed that post-air pageviews "
            "carry more signal than pre-air ones, which raises a different cold-start question: a week after the premiere "
            "a show still has almost no ratings, but its first-week attention is known. Using days 0 to 6 is not "
            "look-ahead for a decision taken on day 7. Mapping, sample, split, models, metric and bootstrap are as in "
            "section 8; definitions are in `src/analyze_after_premiere.py`.")  # fmt: skip
        add("")
        labels = {"meta": "Metadata only", "meta+pre": "+ pre-air pageviews", **{f"meta+pre+first{h}": f"+ first {h} days" for h in horizons}}
        for model, title in (("ridge", "Ridge regression"), ("boosted", "Boosted trees")):
            block = after["models"][model]
            add(f"**{title}**")
            add("")
            add(table(
                ["Information (cumulative)", "Within-season Spearman", "Top-quintile hit rate", "NDCG@10", "Change vs metadata [95% CI]", "Change vs metadata + pre-air [95% CI]"],
                [[label, f"{block['arms'][arm][PRIMARY]:.3f}", f"{block['arms'][arm]['top_quintile_hit_rate']:.3f}", f"{block['arms'][arm]['ndcg_at_10']:.3f}",
                  "—" if arm == "meta" else interval(block["delta_vs_meta"][arm][PRIMARY]),
                  "—" if arm in ("meta", "meta+pre") else interval(block["delta_vs_meta_plus_pre"][arm][PRIMARY])]
                 for arm, label in labels.items()],
            ))  # fmt: skip
            add("")
        add(f"**One test year at a time**, metadata + pre-air + first {after['definitions']['headline_horizon']} days against metadata only")
        add("")
        add(table(
            ["Test year", "n test", "Ridge: change [95% CI]", "Boosted trees: change [95% CI]"],
            [[year, str(b["n_test"]), interval(b["ridge"]["delta_vs_meta"]), interval(b["boosted"]["delta_vs_meta"])] for year, b in after["by_test_year"].items()],
        ))  # fmt: skip
        add("")
        add("The two models disagree. Ridge regression finds no reliable gain from first-week pageviews; boosted trees find one "
            "at every horizon. Both are reported because choosing between them after the fact would be choosing the answer. "
            "A system running on day 7 could also read MAL's own first-week member counts, which this snapshot cannot "
            "reconstruct, so the comparison against the strongest in-domain signal is missing.")  # fmt: skip
        add("")
        add("![Exploratory: information by day](figures/exploratory_fig6_information_by_day.png)")
        add("")

    add("## 10. Limitations")
    add("")
    add("- **Coverage carries look-ahead.** Pageview counts are point-in-time, but whether a title is in Wikidata today "
        "depends on how notable it became. The primary sample conditions on being mapped, so its results describe "
        "titles that have an article, not all new anime.")  # fmt: skip
    add("- **Page moves understate early views.** Views are logged under the title a page had on that day. This can only "
        "weaken the measured pre-air signal.")  # fmt: skip
    add("- **The parent article is often the manga or franchise page.** For those titles the feature measures attention to "
        "the property, not to the anime adaptation specifically.")  # fmt: skip
    add("- **The outcome is one community.** MAL users skew toward English-speaking, engaged fans. The snapshot is from "
        "early 2021, so late-2020 premieres had little time to collect ratings; ranking within a season limits but does "
        "not remove this.")  # fmt: skip
    add("- **The baseline's priors also look ahead slightly.** Studio and franchise priors use earlier titles' outcomes as "
        "of 2021, not as of the premiere. This favours the baseline.")  # fmt: skip
    add("- **Sequel detection is title matching.** The catalog has no franchise column, so some sequels are missed and "
        "some unrelated titles are grouped.")  # fmt: skip
    add("- **MAL's own pre-air signal is not tested.** \"Plan to Watch\" counts exist only as of 2021, after every cohort "
        "title had aired, so the strongest in-domain baseline could not be included.")  # fmt: skip
    add("- **One alt-data source.** Google Trends, Bilibili and others are untested.")
    add("- **This is a feasibility check, not a pre-registered confirmation.** The rule was fixed before the outcome was "
        "examined, but it was not committed to version control beforehand.")  # fmt: skip
    add("")

    add("## 11. Reproduce")
    add("")
    add("Pre-specified analysis:")
    add("")
    add("```bash")
    add("python src/build_cohort.py && python src/map_wikipedia.py && python src/fetch_pageviews.py && python src/analyze.py && python src/figures.py")
    add("```")
    add("")
    add("Exploratory analysis and this report:")
    add("")
    add("```bash")
    add("cd src && python map_wikipedia_exploratory.py && cd .. && python src/fetch_pageviews.py && python src/analyze.py --exploratory && cd src && python analyze_after_premiere.py && cd .. && python src/figures.py --exploratory && python src/report.py")
    add("```")
    add("")
    add("`fetch_pageviews.py` reads an optional `WIKIMEDIA_CONTACT` environment variable (an email or URL). With it the "
        "fetch takes about half an hour; without it Wikimedia's limit for unidentified clients stretches it to about five hours.")  # fmt: skip
    add("")

    (ROOT / "FEASIBILITY.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote FEASIBILITY.md ({len(out)} lines), verdict {decision['verdict']}")


if __name__ == "__main__":
    main()
